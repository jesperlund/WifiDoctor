package com.example.wifidoctor.data.db

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import com.example.wifidoctor.core.history.RunRecord
import com.example.wifidoctor.core.model.Band
import com.example.wifidoctor.core.model.Layer
import com.example.wifidoctor.core.model.Severity
import com.example.wifidoctor.core.model.WifiStandard

/** One persisted diagnostic run (measurements + diagnosis), optionally tagged with a room. */
@Entity(tableName = "runs", indices = [Index("timestampMs"), Index("roomLabel")])
data class RunEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val timestampMs: Long,
    val roomLabel: String?,
    val ssid: String?,
    val bssid: String?,
    val rssiDbm: Int?,
    val linkSpeedMbps: Int?,
    val frequencyMhz: Int?,
    val band: String,
    val channel: Int?,
    val channelWidthMhz: Int?,
    val standard: String,
    val gatewayIp: String?,
    val gatewayAvgMs: Double?,
    val gatewayMaxMs: Double?,
    val gatewayJitterMs: Double?,
    val gatewayLossPercent: Double?,
    val internetTarget: String?,
    val internetAvgMs: Double?,
    val internetMaxMs: Double?,
    val internetJitterMs: Double?,
    val internetLossPercent: Double?,
    val dnsSystemMs: Double?,
    val dnsReferenceMs: Double?,
    val throughputMbps: Double?,
    val sameChannelNetworks: Int?,
    val overlappingNetworks: Int?,
    val countryCode: String? = null,
    val routerChannel24: Int? = null,
    val suggestedChannel24: Int? = null,
    val routerChannel5: Int? = null,
    val suggestedChannel5: Int? = null,
    val suggestedWidth5: Int? = null,
    val severity: String,
    val layer: String?,
    val verdict: String,
    val explanation: String,
    /** Suggested fixes, one per line. */
    val fixes: String,
)

private inline fun <reified E : Enum<E>> enumOr(name: String?, fallback: E): E =
    enumValues<E>().firstOrNull { it.name == name } ?: fallback

fun RunEntity.toRecord(): RunRecord = RunRecord(
    id = id,
    timestampMs = timestampMs,
    roomLabel = roomLabel,
    ssid = ssid,
    bssid = bssid,
    rssiDbm = rssiDbm,
    linkSpeedMbps = linkSpeedMbps,
    frequencyMhz = frequencyMhz,
    band = enumOr(band, Band.UNKNOWN),
    channel = channel,
    channelWidthMhz = channelWidthMhz,
    standard = enumOr(standard, WifiStandard.UNKNOWN),
    gatewayIp = gatewayIp,
    gatewayAvgMs = gatewayAvgMs,
    gatewayMaxMs = gatewayMaxMs,
    gatewayJitterMs = gatewayJitterMs,
    gatewayLossPercent = gatewayLossPercent,
    internetTarget = internetTarget,
    internetAvgMs = internetAvgMs,
    internetMaxMs = internetMaxMs,
    internetJitterMs = internetJitterMs,
    internetLossPercent = internetLossPercent,
    dnsSystemMs = dnsSystemMs,
    dnsReferenceMs = dnsReferenceMs,
    throughputMbps = throughputMbps,
    sameChannelNetworks = sameChannelNetworks,
    overlappingNetworks = overlappingNetworks,
    countryCode = countryCode,
    routerChannel24 = routerChannel24,
    suggestedChannel24 = suggestedChannel24,
    routerChannel5 = routerChannel5,
    suggestedChannel5 = suggestedChannel5,
    suggestedWidth5 = suggestedWidth5,
    severity = enumOr(severity, Severity.OK),
    layer = layer?.let { name -> Layer.entries.firstOrNull { it.name == name } },
    verdict = verdict,
    explanation = explanation,
    fixes = fixes.lines().filter { it.isNotBlank() },
)

fun RunRecord.toEntity(): RunEntity = RunEntity(
    id = id,
    timestampMs = timestampMs,
    roomLabel = roomLabel,
    ssid = ssid,
    bssid = bssid,
    rssiDbm = rssiDbm,
    linkSpeedMbps = linkSpeedMbps,
    frequencyMhz = frequencyMhz,
    band = band.name,
    channel = channel,
    channelWidthMhz = channelWidthMhz,
    standard = standard.name,
    gatewayIp = gatewayIp,
    gatewayAvgMs = gatewayAvgMs,
    gatewayMaxMs = gatewayMaxMs,
    gatewayJitterMs = gatewayJitterMs,
    gatewayLossPercent = gatewayLossPercent,
    internetTarget = internetTarget,
    internetAvgMs = internetAvgMs,
    internetMaxMs = internetMaxMs,
    internetJitterMs = internetJitterMs,
    internetLossPercent = internetLossPercent,
    dnsSystemMs = dnsSystemMs,
    dnsReferenceMs = dnsReferenceMs,
    throughputMbps = throughputMbps,
    sameChannelNetworks = sameChannelNetworks,
    overlappingNetworks = overlappingNetworks,
    countryCode = countryCode,
    routerChannel24 = routerChannel24,
    suggestedChannel24 = suggestedChannel24,
    routerChannel5 = routerChannel5,
    suggestedChannel5 = suggestedChannel5,
    suggestedWidth5 = suggestedWidth5,
    severity = severity.name,
    layer = layer?.name,
    verdict = verdict,
    explanation = explanation,
    fixes = fixes.joinToString("\n") { it.replace('\n', ' ') },
)
